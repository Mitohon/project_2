choice = input("Куда витязь путь держит? (пряму/направу/налеву): ").strip().lower()
if choice == "пряму" or choice == "пряму ехати" or choice == "прямо" or choice == "вперед":
    print ("Живу не бывати :(")
elif choice == "направу" or choice == "направу ехати" or choice == "направо" or choice == "право":
    print ("Женату быти ")
elif choice == "налеву" or choice == "налеву ехати" or choice == "налево" or choice == "лево" :
    print ("Богату быти :D ")