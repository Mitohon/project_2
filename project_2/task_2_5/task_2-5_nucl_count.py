print("=== Анализ последовательности ДНК ===")
dna = input("Введите последовательность ДНК: ").upper()
print(f"\nПоследовательность в верхнем регистре: {dna}")
A = dna.count("A")
T = dna.count("T")
G = dna.count("G")
C = dna.count("C")
len = len(dna)
print("\nПодсчёт нуклеотидов:")
print(f"A: {A}")
print(f"T: {T}")
print(f"G: {G}")
print(f"C: {C}")
print(f"\nОбщая длина: {len} нуклеотидов")
print("\nПроцентное содержание:")
print(f"A: {(A / len * 100):.1f}%")
print(f"T: {(T / len * 100):.1f}%")
print(f"G: {(G / len * 100):.1f}%")
print(f"C: {(C / len * 100):.1f}%")

